def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def sha256_text_file(path: Path) -> str:
    """sha256 of UTF-8 text after universal-newline translation.

    The repaired review tools hash text this way; raw-byte hashing disagrees for
    a CRLF-converted CSV or manifest.
    """
    return sha256_bytes(path.read_text(encoding="utf-8").encode("utf-8"))


def canonical_json(value) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def hash_json(value) -> str:
    return sha256_bytes(canonical_json(value).encode("utf-8"))


def is_placeholder_hash(value) -> bool:
    if not isinstance(value, str):
        return True
    text = value.strip().lower()
    if not re.fullmatch(r"[0-9a-f]{64}", text):
        return True
    if text in PLACEHOLDER_WORDS:
        return True
    if text == EMPTY_SHA256:
        return True
    if len(set(text)) <= 2:
        return True
    return False


def is_iso_timestamp(value) -> bool:
    if not isinstance(value, str) or not value.strip():
        return False
    text = value.strip()
    if not re.search(r"(Z|[+-]\d{2}:?\d{2})$", text):
        return False
    try:
        datetime.fromisoformat(text.replace("Z", "+00:00"))
        return True
    except ValueError:
        return False


def normalize_method(value) -> str:
    raw = str(value or "").strip().lower()
    raw = re.sub(r"[_\s]+", "-", raw)
    if raw in ("platform-export", "platformexport", "export"):
        return "platform-export"
    if raw in ("verbatim-ui", "verbatim", "ui"):
        return "verbatim-ui"
    if raw in ("intended-only", "intended", "planned"):
        return "intended-only"
    return raw


def normalize_artifact_path(value: str):
    if not isinstance(value, str) or not value.strip():
        return None, "artifact path is empty"
    raw = value.strip().replace("\\", "/")
    if raw.startswith("/") or re.match(r"^[A-Za-z]:/", raw):
        return None, "artifact path must be relative, not absolute"
    segments = raw.split("/")
    if any(s == ".." for s in segments):
        return None, "artifact path may not escape the snapshot directory"
    if any(s in ("", ".") for s in segments):
        return None, "artifact path has an empty or '.' segment"
    return "/".join(segments), None


def blocker(code: str, message: str) -> dict:
    return {"code": code, "message": message}


def _collect_artifacts(value, label: str, blockers: list) -> list:
    out = []

    def add(entry):
        if isinstance(entry, str):
            out.append({"path": entry})
            return
        if isinstance(entry, dict):
            if entry.get("path"):
                out.append(entry)
                return
            if isinstance(entry.get("artifacts"), list):
                for child in entry["artifacts"]:
                    add(child)
                return
        blockers.append(blocker(f"artifact-{label}-malformed", f"{label} artifact entry is not {{path, sha256}}"))

    if isinstance(value, list):
        for item in value:
            add(item)
    elif value is not None:
        add(value)
    return out


def _string_list(value, field: str, blockers: list) -> list:
    if value is None:
        blockers.append(blocker(f"{field}-missing", f"snapshot must declare `{field}` as an array"))
        return []
    if not isinstance(value, list):
        blockers.append(blocker(f"{field}-not-array", f"snapshot.{field} must be an array of strings"))
        return []
    out = []
    for i, entry in enumerate(value):
        if not isinstance(entry, str) or not entry.strip():
            blockers.append(blocker(f"{field}-entry-{i}", f"snapshot.{field}[{i}] must be a non-empty string"))
        else:
            out.append(entry.strip())
    return out


def validate_snapshot(snapshot_path: Path) -> dict:
    """Validate a snapshot file and each artifact. Pure read; returns a report."""
    base = {
        "schema": SNAPSHOT_SCHEMA,
        "path": str(snapshot_path),
        "snapshot_sha256": None,
        "status": "invalid",
        "ok": False,
        "project_id": None,
        "model": None,
        "captured_at": None,
        "method": None,
        "current_effective_config_verified": None,
        "config_hash": None,
        "artifact_hashes": {"instructions": [], "knowledge": [], "ui_settings": []},
        "normalized": None,
        "blockers": [],
        "warnings": [],
    }
    path = Path(snapshot_path)
    if not path.is_file():
        base["blockers"].append(blocker("snapshot-absent", f"snapshot does not exist: {path}"))
        return base
    raw = path.read_bytes()
    base["snapshot_sha256"] = sha256_bytes(raw)
    try:
        snap = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        base["blockers"].append(blocker("snapshot-json", f"snapshot is not valid JSON: {exc}"))
        return base
    if not isinstance(snap, dict):
        base["blockers"].append(blocker("snapshot-not-object", "snapshot is not a JSON object"))
        return base

    blockers = base["blockers"]
    warnings = base["warnings"]
    snapshot_dir = path.parent

    if snap.get("schema") != SNAPSHOT_SCHEMA:
        blockers.append(blocker("snapshot-schema", f'snapshot.schema must be "{SNAPSHOT_SCHEMA}"'))

    project_id = str(snap.get("project_id") or "").strip()
    if not project_id:
        blockers.append(blocker("project-id-missing", "snapshot.project_id is required"))
    elif not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{2,63}", project_id):
        blockers.append(blocker("project-id-shape", f"snapshot.project_id is not a platform id: {project_id}"))
    elif re.fullmatch(r"(project|unknown|todo|tbd|none|example|sample)", project_id, re.I):
        blockers.append(blocker("project-id-placeholder", f"snapshot.project_id is a placeholder: {project_id}"))

    model_value = snap.get("model")
    if isinstance(model_value, dict):
        model_value = model_value.get("name") or model_value.get("id")
    model = str(model_value or "").strip()
    if not model:
        blockers.append(blocker("model-missing", 'snapshot.model is required (expected "Luna")'))
    elif model.lower() != "luna":
        blockers.append(blocker("model-not-luna", f"snapshot.model must be Luna (got {model})"))

    capture = snap.get("capture")
    if not isinstance(capture, dict):
        blockers.append(blocker("capture-missing", "snapshot.capture object is required"))
        capture = {}
    method = normalize_method(capture.get("method", snap.get("method")))
    if method not in CAPTURE_METHODS:
        blockers.append(blocker("capture-method", f"snapshot.capture.method must be one of {', '.join(CAPTURE_METHODS)}"))
    if method == "intended-only":
        blockers.append(blocker(
            "intended-only-not-effective",
            "intended-only manifests describe what was intended; they are never evidence of the effective published configuration",
        ))
    captured_at = str(capture.get("captured_at") or snap.get("captured_at") or "").strip()
    if not is_iso_timestamp(captured_at):
        blockers.append(blocker("captured-at-invalid", "snapshot.capture.captured_at must be ISO-8601 with an offset or Z"))
    export_scope = str(capture.get("export_scope") or "").strip().lower()
    if export_scope in ("full", "complete", "effective-complete", "all"):
        blockers.append(blocker(
            "export-scope-overclaimed",
            "the platform does not expose a complete effective configuration; export_scope cannot be full/complete",
        ))
    elif not export_scope:
        warnings.append(blocker(
            "export-scope-unstated",
            "capture.export_scope is unstated; hidden platform configuration remains unknown",
        ))
    current_verified = capture.get("current_effective_config_verified")
    if current_verified is False:
        blockers.append(blocker(
            "current-config-not-verified",
            "capture states the current effective configuration was not verified; a historical read-back is not a current publication snapshot",
        ))
    elif current_verified is not True:
        blockers.append(blocker(
            "current-config-verification-missing",
            "capture.current_effective_config_verified must be true to treat this snapshot as evidence of the current publication",
        ))

    publication = capture.get("publication")
    if publication is None:
        publication = snap.get("publication")
    revision = capture.get("revision")
    if revision is None:
        revision = snap.get("revision")

    def placeholder_value(value) -> bool:
        if value is None:
            return True
        if isinstance(value, str):
            text = value.strip().lower()
            return not text or text in PLACEHOLDER_WORDS or bool(re.fullmatch(r"<.*>", text))
        if isinstance(value, (list, dict)):
            return len(value) == 0
        return False

    if publication is not None and placeholder_value(publication):
        blockers.append(blocker("publication-placeholder", "snapshot publication is present but empty/placeholder"))
    if revision is not None and placeholder_value(revision):
        blockers.append(blocker("revision-placeholder", "snapshot revision is present but empty/placeholder"))
    if publication is None:
        warnings.append(blocker("publication-not-exposed", "publication metadata is absent; record it under unknowns"))
    if revision is None:
        warnings.append(blocker("revision-not-exposed", "revision metadata is absent; record it under unknowns"))

    unknowns = _string_list(snap.get("unknowns"), "unknowns", blockers)
    limitations = _string_list(snap.get("limitations"), "limitations", blockers)

    artifacts_raw = snap.get("artifacts")
    if not isinstance(artifacts_raw, dict):
        blockers.append(blocker("artifacts-missing", "snapshot.artifacts object is required"))
        artifacts_raw = {}
    artifacts = {"instructions": [], "knowledge": [], "ui_settings": []}
    minimums = {"instructions": 16, "knowledge": 1, "ui_settings": 1}
    for category in ("instructions", "knowledge", "ui_settings"):
        entries = _collect_artifacts(artifacts_raw.get(category), category, blockers)
        if not entries:
            blockers.append(blocker(
                f"artifact-{category}-missing",
                f"snapshot.artifacts.{category} must name at least one captured, hashed artifact",
            ))
            continue
        for entry in entries:
            rel, err = normalize_artifact_path(entry.get("path"))
            if rel is None:
                blockers.append(blocker(f"artifact-{category}-path", err or "invalid path"))
                continue
            absolute = (snapshot_dir / rel).resolve()
            try:
                inside = absolute.is_relative_to(snapshot_dir.resolve()) and absolute != snapshot_dir.resolve()
            except AttributeError:  # Python 3.8
                try:
                    absolute.relative_to(snapshot_dir.resolve())
                    inside = absolute != snapshot_dir.resolve()
                except ValueError:
                    inside = False
            if not inside:
                blockers.append(blocker(f"artifact-{category}-escape", f"{rel} resolves outside the snapshot directory"))
                continue
            if not absolute.is_file():
                blockers.append(blocker(f"artifact-{category}-absent", f"{rel} does not exist beside the snapshot"))
                continue
            data = absolute.read_bytes()
            actual = sha256_bytes(data)
            if not data:
                blockers.append(blocker(f"artifact-{category}-empty", f"{rel} is empty"))
            elif not data.decode("utf-8", errors="replace").strip():
                blockers.append(blocker(f"artifact-{category}-blank", f"{rel} contains only whitespace"))
            elif len(data) < minimums[category]:
                blockers.append(blocker(f"artifact-{category}-too-small", f"{rel} is smaller than {minimums[category]} bytes"))
            recorded = entry.get("sha256")
            if recorded is None:
                blockers.append(blocker(f"artifact-{category}-sha-missing", f"{rel} has no recorded sha256"))
            elif is_placeholder_hash(recorded):
                blockers.append(blocker(f"artifact-{category}-sha-placeholder", f"{rel} has a placeholder/invalid sha256"))
            elif str(recorded).lower() != actual:
                blockers.append(blocker(f"artifact-{category}-sha-mismatch", f"{rel} recorded sha256 does not match the bytes on disk"))
            if entry.get("bytes") is not None:
                try:
                    recorded_bytes = int(entry["bytes"])
                except (TypeError, ValueError):
                    recorded_bytes = None
                if recorded_bytes is not None and recorded_bytes != len(data):
                    blockers.append(blocker(f"artifact-{category}-bytes-mismatch", f"{rel} recorded byte count does not match"))
            artifacts[category].append({"path": rel, "sha256": actual, "bytes": len(data)})

    public_url = None
    agent = snap.get("agent") if isinstance(snap.get("agent"), dict) else {}
    if agent.get("public_url") is not None:
        candidate = str(agent["public_url"])
        if re.match(r"^https?://", candidate):
            public_url = candidate
        else:
            blockers.append(blocker("agent-public-url-invalid", "snapshot.agent.public_url is not an http(s) URL"))
    if agent.get("project_id") is not None and str(agent["project_id"]).strip() != project_id:
        blockers.append(blocker("agent-project-mismatch", "snapshot.agent.project_id does not match snapshot.project_id"))

    config_material = {
        "project_id": project_id,
        "model": "Luna",
        "capture_method": method,
        "current_effective_config_verified": current_verified is True,
        "publication": publication,
        "revision": revision,
        "public_url": public_url,
        "artifacts": {
            "instructions": [{"path": a["path"], "sha256": a["sha256"]} for a in artifacts["instructions"]],
            "knowledge": [{"path": a["path"], "sha256": a["sha256"]} for a in artifacts["knowledge"]],
            "ui_settings": [{"path": a["path"], "sha256": a["sha256"]} for a in artifacts["ui_settings"]],
        },
        "unknowns": unknowns,
        "limitations": limitations,
    }
    config_hash = hash_json(config_material)

    base.update({
        "ok": not blockers,
        "status": "verified-effective" if not blockers else "invalid",
        "project_id": project_id or None,
        "model": "Luna" if model else None,
        "captured_at": captured_at or None,
        "method": method or None,
        "current_effective_config_verified": current_verified is True,
        "config_hash": config_hash,
        "artifact_hashes": artifacts,
        "normalized": {
            "schema": SNAPSHOT_SCHEMA,
            "project_id": project_id,
            "model": "Luna",
            "capture": {
                "method": method,
                "captured_at": captured_at,
                "publication": publication,
                "revision": revision,
                "export_scope": export_scope or None,
                "current_effective_config_verified": current_verified is True,
            },
            "agent": {"public_url": public_url},
            "artifacts": artifacts,
            "unknowns": unknowns,
            "limitations": limitations,
            "config_hash": config_hash,
        },
    })
    return base


def _load_json(path: Path, code: str, blockers: list):
    if not path.is_file():
        blockers.append(blocker(code, f"missing file: {path}"))
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        blockers.append(blocker(code, f"{path} is not valid JSON: {exc}"))
        return None


def validate_scenarios(path: Path, graders_path: Path) -> dict:
    """Check scenario ids and that each has a prospective grader."""
    blockers, warnings = [], []
    data = _load_json(path, "scenarios-json", blockers)
    if data is None:
        _load_json(graders_path, "graders-json", blockers)
        return {"ok": False, "blockers": blockers, "warnings": warnings, "ids": [], "count": 0}

    items = data.get("scenarios") if isinstance(data.get("scenarios"), list) else data.get("scripts")
    if not isinstance(items, list) or not items:
        blockers.append(blocker("scenarios-empty", "scenario set has no scenarios/scripts array"))
        return {"ok": False, "blockers": blockers, "warnings": warnings, "ids": [], "count": 0}

    ids = []
    for index, item in enumerate(items):
        if not isinstance(item, dict):
            blockers.append(blocker("scenario-shape", f"scenario[{index}] is not an object"))
            continue
        sid = str(item.get("id") or "").strip()
        if not sid:
            blockers.append(blocker("scenario-id", f"scenario[{index}] has no id"))
            continue
        ids.append(sid)
        if "customer" in item:
            if not isinstance(item["customer"], str) or not item["customer"].strip():
                blockers.append(blocker("scenario-customer", f"{sid} has no customer text"))
        elif "turns" in item:
            turns = item["turns"]
            if not isinstance(turns, list) or not turns or any(not isinstance(t, str) or not t.strip() for t in turns):
                blockers.append(blocker("scenario-turns", f"{sid} has no usable turns"))
        else:
            blockers.append(blocker("scenario-text", f"{sid} has neither customer nor turns"))
    duplicates = sorted({sid for sid in ids if ids.count(sid) > 1})
    if duplicates:
        blockers.append(blocker("scenario-duplicate-ids", f"duplicate scenario ids: {', '.join(duplicates[:5])}"))

    graders = _load_json(graders_path, "graders-json", blockers)
    if graders is not None:
        table = graders.get("scenarios") if isinstance(graders.get("scenarios"), dict) else graders.get("scripts")
        if not isinstance(table, dict):
            blockers.append(blocker("graders-shape", "graders file has no scenarios/scripts object"))
        else:
            missing = [sid for sid in ids if sid not in table]
            if missing:
                blockers.append(blocker(
                    "graders-missing",
                    f"{len(missing)} of {len(ids)} scenarios have no prospective grader: {', '.join(missing[:6])}",
                ))
            extra = [sid for sid in table if sid not in ids]
            if extra:
                warnings.append(blocker("graders-extra", f"{len(extra)} grader(s) have no scenario: {', '.join(extra[:5])}"))
            empty = [sid for sid in ids if sid in table and not isinstance(table[sid], dict)]
            if empty:
                blockers.append(blocker("graders-shape-entry", f"grader entries are not objects: {', '.join(empty[:5])}"))

    return {"ok": not blockers, "blockers": blockers, "warnings": warnings, "ids": ids, "count": len(ids)}


def validate_controls(path: Path) -> dict:
    blockers, warnings = [], []
    data = _load_json(path, "controls-json", blockers)
    if data is None:
        return {"ok": False, "blockers": blockers, "warnings": warnings, "count": 0}
    items = data.get("controls") if isinstance(data.get("controls"), list) else data.get("scenarios")
    if not isinstance(items, list) or not items:
        blockers.append(blocker("controls-empty", "controls file has no controls/scenarios array"))
        return {"ok": False, "blockers": blockers, "warnings": warnings, "count": 0}
    ids, kinds, expectations = [], [], []
    for index, item in enumerate(items):
        if not isinstance(item, dict):
            blockers.append(blocker("controls-shape", f"control[{index}] is not an object"))
            continue
        cid = str(item.get("id") or "").strip()
        if not cid:
            blockers.append(blocker("control-id", f"control[{index}] has no id"))
            continue
        ids.append(cid)
        expected = item.get("expected", item.get("expect"))
        if expected is not None:
            value = str(expected).strip().upper()
            if value not in ("PASS", "FAIL", "UNSURE", "AMBIGUOUS"):
                blockers.append(blocker("control-expect", f"{cid} expected/expect must be PASS, FAIL, or UNSURE"))
            else:
                expectations.append("UNSURE" if value in ("UNSURE", "AMBIGUOUS") else value)
        if item.get("kind"):
            kinds.append(str(item["kind"]).lower())
        if item.get("category"):
            kinds.append(str(item["category"]).lower())
    duplicates = sorted({cid for cid in ids if ids.count(cid) > 1})
    if duplicates:
        blockers.append(blocker("control-duplicate-ids", f"duplicate control ids: {', '.join(duplicates[:5])}"))
    if len(ids) < 2:
        warnings.append(blocker("controls-few", "fewer than two controls; a positive/negative pair is stronger"))
    if expectations and not {"PASS", "FAIL"} <= set(expectations):
        warnings.append(blocker("controls-coverage", "controls do not include both a PASS and a FAIL expectation"))
    return {"ok": not blockers, "blockers": blockers, "warnings": warnings, "count": len(ids)}



def _norm_verdict(value) -> str:
    text = str(value or "").strip().upper()
    if text in ("UNSURE", "AMBIGUOUS"):
        return "UNSURE"
    return text


def _valid_receipt_hash(value) -> bool:
    if not isinstance(value, str):
        return False
    text = value.strip().lower()
    return re.fullmatch(r"[0-9a-f]{64}", text) is not None and not is_placeholder_hash(text)


def _bind_receipt_file(binding, base_dir: Path, label: str, blockers: list,
                       expected_sha: str | None = None,
                       expected_path: Path | None = None) -> Path | None:
    if not isinstance(binding, dict) or not binding.get("path") or not binding.get("sha256"):
        blockers.append(blocker(f"{label}-binding", f"{label} must declare path and sha256"))
        return None
    path = Path(str(binding["path"]))
    if not path.is_absolute():
        path = base_dir / path
    if not path.is_file():
        blockers.append(blocker(f"{label}-absent", f"{label} file is missing: {path}"))
        return None
    actual = sha256_file(path)
    if not _valid_receipt_hash(binding["sha256"]) or str(binding["sha256"]).lower() != actual:
        blockers.append(blocker(f"{label}-sha", f"{label} sha256 does not match the file"))
    if expected_sha and actual != expected_sha:
        blockers.append(blocker(f"{label}-expected-sha", f"{label} does not hash to the declared configuration file"))
    if expected_path and path.resolve() != expected_path.resolve():
        blockers.append(blocker(f"{label}-path", f"{label} points at a different file than the declared configuration"))
    return path


def validate_control_results(receipt_path: Path, controls_path: Path, graders_path: Path,
                             expected_controls_sha: str | None,
                             expected_graders_sha: str | None) -> dict:
    """Validate agentplace-control-results-v1 against the controls and graders.

    A controls stage marked complete is only evidence if a receipt proves each
    declared control's expected outcome was actually observed by the prospective
    grader. Missing/extra/duplicate ids or a single mismatch are refusals.
    """
    blockers, warnings = [], []
    data = _load_json(receipt_path, "control-results-json", blockers)
    if data is None:
        return {"ok": False, "blockers": blockers, "warnings": warnings, "count": 0}
    if data.get("schema") != CONTROL_RESULTS_SCHEMA:
        blockers.append(blocker("control-results-schema", f"receipt schema must be {CONTROL_RESULTS_SCHEMA}"))
    if data.get("status") != "passed":
        blockers.append(blocker("control-results-status", "control results status must be passed"))
    if not is_iso_timestamp(data.get("completed_at")):
        blockers.append(blocker("control-results-completed-at", "control results need an ISO-8601 completed_at"))

    _bind_receipt_file(data.get("controls"), receipt_path.parent, "control-results.controls",
                       blockers, expected_controls_sha, controls_path)
    _bind_receipt_file(data.get("graders"), receipt_path.parent, "control-results.graders",
                       blockers, expected_graders_sha, graders_path)

    controls_doc = _load_json(controls_path, "controls-json", blockers)
    items = []
    if isinstance(controls_doc, dict):
        items = controls_doc.get("controls") if isinstance(controls_doc.get("controls"), list) else controls_doc.get("scenarios")
    expectations = {}
    if isinstance(items, list):
        for item in items:
            if not isinstance(item, dict):
                continue
            cid = str(item.get("id") or "").strip()
            if cid:
                expectations[cid] = _norm_verdict(item.get("expected", item.get("expect")))

    results = data.get("results")
    seen = {}
    if not isinstance(results, list) or not results:
        blockers.append(blocker("control-results-empty", "receipt must list one result per declared control"))
        results = []
    for index, row in enumerate(results):
        if not isinstance(row, dict):
            blockers.append(blocker("control-results-row", f"result[{index}] is not an object"))
            continue
        cid = str(row.get("control_id") or row.get("id") or "").strip()
        expected = _norm_verdict(row.get("expected"))
        observed = _norm_verdict(row.get("observed"))
        match = row.get("match")
        if cid not in expectations:
            blockers.append(blocker("control-results-extra", f"result[{index}] names unknown control {cid!r}"))
            continue
        if cid in seen:
            blockers.append(blocker("control-results-duplicate", f"duplicate control result for {cid}"))
            continue
        seen[cid] = row
        if expected != expectations[cid]:
            blockers.append(blocker("control-results-expected", f"{cid} expected {expected} does not match the controls file"))
        if observed not in ("PASS", "FAIL", "UNSURE"):
            blockers.append(blocker("control-results-observed", f"{cid} observed outcome is not PASS/FAIL/UNSURE"))
        if bool(match) is not (expected == observed):
            blockers.append(blocker("control-results-match", f"{cid} match flag contradicts expected/observed"))
    missing = [cid for cid in expectations if cid not in seen]
    if missing:
        blockers.append(blocker(
            "control-results-missing",
            f"{len(missing)} declared control(s) have no result: {', '.join(missing[:6])}",
        ))

    counts = data.get("counts")
    if not isinstance(counts, dict):
        blockers.append(blocker("control-results-counts", "receipt counts object is required"))
    else:
        try:
            total = int(counts.get("total"))
            matched = int(counts.get("matched"))
            mismatched = int(counts.get("mismatched"))
        except (TypeError, ValueError):
            blockers.append(blocker("control-results-counts", "counts total/matched/mismatched must be integers"))
        else:
            if total != len(expectations):
                blockers.append(blocker("control-results-count-total", "counts.total does not equal the declared control count"))
            if matched != len(results):
                blockers.append(blocker("control-results-count-matched", "counts.matched does not equal the result count"))
            if mismatched != 0:
                blockers.append(blocker("control-results-mismatch", "control results report mismatched outcomes"))
    return {
        "ok": not blockers,
        "blockers": blockers,
        "warnings": warnings,
        "count": len(results),
        "status": data.get("status"),
    }


def validate_scoring_receipt(score_path: Path, guide_path: Path,
                             blind_manifest_path: Path | None = None,
                             returned_sheet_path: Path | None = None,
                             reviewed_attested: bool = False) -> dict:
    """Validate the repaired modern score object as the human-label receipt.

    Accepted format is exactly agentplace-blind-score/1. A legacy-dir object,
    a zero-scored object, a missing labels_complete/reviewed flag, a changed
    guide hash, a missing source-manifest hash, or a blank/partial sheet is
    refused. The manifest stage path+sha256 binds this file.
    """
    blockers, warnings = [], []
    data = _load_json(score_path, "score-json", blockers)
    if data is None:
        return {"ok": False, "blockers": blockers, "warnings": warnings, "counts": None}
    if data.get("format") != SCORING_RECEIPT_SCHEMA:
        blockers.append(blocker("score-format", f"score format must be {SCORING_RECEIPT_SCHEMA}"))
    if data.get("labels_complete") is not True:
        blockers.append(blocker("score-labels-incomplete", "score object must carry labels_complete=true"))
    if data.get("reviewed") is not True and reviewed_attested is not True:
        blockers.append(blocker("score-not-reviewed", "calibration review must be attested by score.reviewed=true or stages.human_labels.reviewed=true"))

    try:
        n_total = int(data.get("n_total"))
        n_scored = int(data.get("n_scored"))
        n_unsure = int(data.get("n_unsure"))
    except (TypeError, ValueError):
        n_total = n_scored = n_unsure = None
    if n_total is None:
        blockers.append(blocker("score-counts", "n_total/n_scored/n_unsure must be integers"))
    else:
        if n_total <= 0 or n_scored <= 0:
            blockers.append(blocker("score-zero-scored", "a completed receipt needs a positive n_total and n_scored; zero-scored is refused"))
        if n_scored + n_unsure != n_total:
            blockers.append(blocker("score-partial", "n_scored + n_unsure does not equal n_total: blank or missing labels remain"))
        detail = data.get("detail")
        if detail is not None and (not isinstance(detail, list) or len(detail) != n_scored):
            blockers.append(blocker("score-detail", "detail length does not equal n_scored"))
        unsure_detail = data.get("unsure_detail")
        if not isinstance(unsure_detail, list):
            blockers.append(blocker("score-unsure-detail", "unsure_detail list is required (preserve all UNSURE rows)"))
        elif len(unsure_detail) != n_unsure:
            blockers.append(blocker("score-unsure-count", "unsure_detail length does not equal n_unsure"))
        row_counts = data.get("row_counts")
        if not isinstance(row_counts, dict):
            blockers.append(blocker("score-row-counts", "row_counts object is required"))
        else:
            try:
                expected_rows = int(row_counts.get("expected"))
                scored_rows = int(row_counts.get("scored"))
                unsure_rows = int(row_counts.get("unsure"))
                blank_rows = int(row_counts.get("blank"))
                missing_rows = int(row_counts.get("missing"))
                invalid_rows = int(row_counts.get("invalid"))
            except (TypeError, ValueError):
                blockers.append(blocker("score-row-counts", "row_counts values must be integers"))
            else:
                if expected_rows != n_total or scored_rows != n_scored or unsure_rows != n_unsure:
                    blockers.append(blocker("score-row-counts-mismatch", "row_counts do not match n_total/n_scored/n_unsure"))
                if blank_rows or missing_rows or invalid_rows:
                    blockers.append(blocker("score-incomplete-rows", "row_counts report blank, missing or invalid rows"))

    guide_candidates = set()
    if guide_path.is_file():
        guide_candidates.add(sha256_file(guide_path))
        guide_candidates.add(sha256_text_file(guide_path))
    guide_hash = data.get("guide_sha256")
    if not _valid_receipt_hash(guide_hash):
        blockers.append(blocker("score-guide-hash", "guide_sha256 must be a real sha256"))
    elif guide_candidates and str(guide_hash).lower() not in guide_candidates:
        blockers.append(blocker("score-guide-mismatch", "guide_sha256 does not match the current guide"))
    for field in ("key_sha256", "sheet_sha256", "source_manifest_sha256"):
        if not _valid_receipt_hash(data.get(field)):
            blockers.append(blocker(f"score-{field}", f"{field} must be a real sha256"))
    returned_sheet = data.get("returned_sheet_sha256")
    if not _valid_receipt_hash(returned_sheet):
        blockers.append(blocker(
            "score-returned-sheet-hash",
            "returned_sheet_sha256 must hash the filled CSV the labeller returned; it is distinct from the original sheet_sha256",
        ))
    elif str(returned_sheet).lower() == str(data.get("sheet_sha256", "")).lower():
        blockers.append(blocker(
            "score-returned-sheet-unchanged",
            "returned_sheet_sha256 equals the original blank sheet hash; the blank export cannot evidence completed labels",
        ))
    elif returned_sheet_path is not None:
        if not returned_sheet_path.is_file():
            blockers.append(blocker("score-returned-sheet-absent", f"returned sheet is missing: {returned_sheet_path}"))
        else:
            actual_returned = sha256_text_file(returned_sheet_path)
            if actual_returned != str(returned_sheet).lower():
                blockers.append(blocker(
                    "score-returned-sheet-mismatch",
                    "returned_sheet_sha256 does not match the normalized returned CSV",
                ))
            if actual_returned == str(data.get("sheet_sha256", "")).lower():
                blockers.append(blocker(
                    "score-returned-sheet-blank",
                    "the returned CSV hash equals the frozen blank sheet hash; no filled sheet was returned",
                ))
    else:
        blockers.append(blocker(
            "score-returned-sheet-path",
            "a returned-sheet path is required to verify returned_sheet_sha256",
        ))
    if not str(data.get("batch") or "").strip():
        blockers.append(blocker("score-batch", "score batch is required"))
    if not isinstance(data.get("metrics"), dict):
        blockers.append(blocker("score-metrics", "score metrics object is required"))

    if blind_manifest_path:
        manifest_data = _load_json(blind_manifest_path, "blind-manifest-json", blockers)
        if isinstance(manifest_data, dict):
            if manifest_data.get("format") != "agentplace-blind-manifest/1":
                blockers.append(blocker("blind-manifest-format", "blind manifest format must be agentplace-blind-manifest/1"))
            manifest_candidates = {sha256_file(blind_manifest_path), sha256_text_file(blind_manifest_path)}
            if _valid_receipt_hash(data.get("source_manifest_sha256")) and str(data["source_manifest_sha256"]).lower() not in manifest_candidates:
                blockers.append(blocker("score-source-manifest", "source_manifest_sha256 does not match the supplied blind manifest"))
            guide_meta = manifest_data.get("guide") if isinstance(manifest_data.get("guide"), dict) else {}
            if guide_meta.get("sha256") and str(guide_meta["sha256"]).lower() != str(guide_hash).lower():
                blockers.append(blocker("score-manifest-guide", "score guide hash does not match the blind manifest"))
            if manifest_data.get("sheet_sha256") and str(manifest_data["sheet_sha256"]).lower() != str(data.get("sheet_sha256", "")).lower():
                blockers.append(blocker("score-manifest-sheet", "score sheet hash does not match the blind manifest"))
            if manifest_data.get("key_sha256") and str(manifest_data["key_sha256"]).lower() != str(data.get("key_sha256", "")).lower():
                blockers.append(blocker("score-manifest-key", "score key hash does not match the blind manifest"))
    elif _valid_receipt_hash(data.get("source_manifest_sha256")):
        warnings.append(blocker(
            "blind-manifest-not-cross-checked",
            "no --blind-manifest supplied; the score's source_manifest_sha256 was not checked against the file",
        ))
    return {
        "ok": not blockers,
        "blockers": blockers,
        "warnings": warnings,
        "counts": {"n_total": n_total, "n_scored": n_scored, "n_unsure": n_unsure},
    }


def validate_manifest(path: Path, mode: str) -> dict:
    blockers, warnings = [], []
    data = _load_json(path, "manifest-json", blockers)
    if data is None:
        return {"ok": False, "blockers": blockers, "warnings": warnings, "manifest": None}
    if data.get("schema") != MANIFEST_SCHEMA:
        blockers.append(blocker("manifest-schema", f"manifest.schema must be {MANIFEST_SCHEMA}"))
    run_id = str(data.get("run_id") or "").strip()
    if not run_id:
        blockers.append(blocker("manifest-run-id", "manifest.run_id is required"))
    phase = str(data.get("phase") or "").strip()
    if not phase:
        blockers.append(blocker("manifest-phase", "manifest.phase is required"))
    authorized = data.get("collection_authorized")
    if authorized is False:
        blockers.append(blocker(
            "collection-not-authorized",
            "manifest explicitly marks collection_authorized=false; preparation only, no capture is authorized",
        ))
    elif authorized is not True:
        blockers.append(blocker(
            "collection-authorization-missing",
            "manifest must explicitly set collection_authorized=true before a capture preflight can be ready",
        ))
    manifest_status = str(data.get("status") or "").strip().lower()
    if manifest_status in ("preparation_only", "preparation-only", "blocked", "draft", "not_ready", "not-ready"):
        blockers.append(blocker("manifest-not-ready", f"manifest status is {manifest_status!r}, not a ready collection state"))

    stages = data.get("stages")
    if not isinstance(stages, dict):
        blockers.append(blocker("manifest-stages", "manifest.stages object is required"))
        stages = {}
    for stage in REQUIRED_STAGES:
        if stage not in stages:
            blockers.append(blocker(f"manifest-stage-{stage}-missing", f"manifest.stages.{stage} is missing"))
            continue
        entry = stages[stage]
        if not isinstance(entry, dict):
            blockers.append(blocker(f"manifest-stage-{stage}-shape", f"manifest.stages.{stage} must be an object"))
            continue
        status = str(entry.get("status") or "").strip()
        if status not in STAGE_STATUSES:
            blockers.append(blocker(f"manifest-stage-{stage}-status", f"manifest.stages.{stage}.status is invalid"))
        elif status != "complete":
            blockers.append(blocker(
                f"manifest-stage-{stage}-not-complete",
                f"manifest.stages.{stage} is {status}; a ready capture needs complete configuration artifacts",
            ))
    if "human_labels" not in stages:
        blockers.append(blocker(
            "manifest-stage-human_labels-missing",
            "manifest.stages.human_labels is missing; declare it with a completed, reviewed modern score receipt",
        ))
    else:
        entry = stages["human_labels"]
        if not isinstance(entry, dict):
            blockers.append(blocker("manifest-stage-human_labels-shape", "manifest.stages.human_labels must be an object"))
        else:
            status = str(entry.get("status") or "").strip()
            if status not in STAGE_STATUSES:
                blockers.append(blocker("manifest-stage-human_labels-status", "human_labels status is invalid"))
            elif status != "complete":
                owner = str(entry.get("owner") or "").strip()
                blockers.append(blocker(
                    "human-labels-not-complete",
                    "human calibration must be completed and reviewed before capture as well as before scoring"
                    + (f"; pending owner: {owner}" if owner else "; no owner is named"),
                ))
            elif not entry.get("path"):
                blockers.append(blocker("human-labels-path-missing", "completed human labels must name the modern score receipt"))
            elif not entry.get("sha256"):
                blockers.append(blocker("human-labels-sha-missing", "completed human labels must bind the score receipt by sha256"))
            else:
                label_path = Path(entry["path"])
                if not label_path.is_absolute():
                    label_path = path.parent / label_path
                if not label_path.is_file():
                    blockers.append(blocker("human-labels-path", f"completed label receipt does not exist: {label_path}"))
                elif is_placeholder_hash(entry.get("sha256")) or sha256_file(label_path) != str(entry["sha256"]).lower():
                    blockers.append(blocker("human-labels-sha", "human label receipt changed since the manifest was written"))
            if status == "complete" and entry.get("reviewed") is not True:
                blockers.append(blocker(
                    "human-labels-review-missing",
                    "completed human calibration must be attested by stages.human_labels.reviewed=true",
                ))

    controls_entry = stages.get("controls") if isinstance(stages.get("controls"), dict) else {}
    if controls_entry.get("status") == "complete":
        results_entry = controls_entry.get("results")
        if not isinstance(results_entry, dict) or not results_entry.get("path") or not results_entry.get("sha256"):
            blockers.append(blocker(
                "manifest-control-results-missing",
                "a complete controls stage must bind an agentplace-control-results-v1 receipt by path and sha256",
            ))
        else:
            receipt_path = Path(str(results_entry["path"]))
            if not receipt_path.is_absolute():
                receipt_path = path.parent / receipt_path
            if not receipt_path.is_file():
                blockers.append(blocker("manifest-control-results-absent", f"control results receipt is missing: {receipt_path}"))
            elif is_placeholder_hash(results_entry.get("sha256")) or sha256_file(receipt_path) != str(results_entry["sha256"]).lower():
                blockers.append(blocker("manifest-control-results-sha", "control results receipt changed since the manifest was written"))

    artifacts = data.get("artifacts")
    if artifacts is not None and not isinstance(artifacts, dict):
        blockers.append(blocker("manifest-artifacts-shape", "manifest.artifacts must be an object of path -> sha256"))
    elif isinstance(artifacts, dict):
        for rel, expected in artifacts.items():
            artifact_path = Path(rel)
            if not artifact_path.is_absolute():
                artifact_path = path.parent / artifact_path
            if not artifact_path.is_file():
                blockers.append(blocker("manifest-artifact-absent", f"manifest artifact is missing: {rel}"))
            elif not is_placeholder_hash(expected) and sha256_file(artifact_path) != str(expected).lower():
                blockers.append(blocker("manifest-artifact-sha", f"manifest artifact hash changed: {rel}"))

    pair_execution = data.get("pair_execution")
    if isinstance(pair_execution, dict):
        try:
            completed_declared = int(pair_execution.get("completed_pairs") or 0)
        except (TypeError, ValueError):
            completed_declared = 0
        if completed_declared > 0:
            blockers.append(blocker(
                "pair-completion-unsupported",
                "manifest claims completed pairs, but no pair execution evidence exists",
            ))
    if isinstance(pair_execution, bool) and pair_execution:
        warnings.append(blocker("pair-execution-planned", "manifest declares paired execution; completion still requires paired-state evidence"))

    return {
        "ok": not blockers,
        "blockers": blockers,
        "warnings": warnings,
        "manifest": data,
        "run_id": run_id or None,
        "phase": phase or None,
        "stages": stages,
    }


def validate_schedule(path: Path) -> dict:
    blockers, warnings = [], []
    data = _load_json(path, "schedule-json", blockers)
    if data is None:
        return {"ok": False, "blockers": blockers, "warnings": warnings, "schedule": None, "count": 0}
    if data.get("schema") != SCHEDULE_SCHEMA:
        blockers.append(blocker("schedule-schema", f"schedule.schema must be {SCHEDULE_SCHEMA}"))
    arms = data.get("arms")
    if not isinstance(arms, list) or len(arms) != 2:
        blockers.append(blocker("schedule-arms", "schedule.arms must contain exactly two arm ids"))
        arms = []
    if data.get("pair_execution_implemented") is True:
        blockers.append(blocker("schedule-claims-execution", "an immutable schedule must not claim execution; paired state is the evidence"))
    try:
        declared_completed = int(data.get("completed_pairs") or 0)
    except (TypeError, ValueError):
        declared_completed = 0
    if declared_completed > 0:
        blockers.append(blocker("schedule-completed-claims", "schedule claims completed pairs without recorded evidence"))
    try:
        reps = int(data.get("reps") or 1)
    except (TypeError, ValueError):
        reps = 1
    if reps != 1:
        blockers.append(blocker(
            "schedule-reps-unsupported",
            "the runners record trials without a rep label; a schedule with reps > 1 cannot be executed honestly",
        ))

    pairs = data.get("pairs")
    if not isinstance(pairs, list) or not pairs:
        blockers.append(blocker("schedule-pairs", "schedule has no pairs"))
        return {"ok": not blockers, "blockers": blockers, "warnings": warnings, "schedule": data, "count": 0}

    seen = set()
    cell_seen = set()
    by_scenario = {}
    for index, pair in enumerate(pairs):
        if not isinstance(pair, dict):
            blockers.append(blocker("schedule-pair-shape", f"pair[{index}] is not an object"))
            continue
        pid = str(pair.get("pair_id") or "").strip()
        scenario = str(pair.get("scenario") or "").strip()
        trial = pair.get("trial")
        order = str(pair.get("order") or "").strip().upper()
        pair_arms = pair.get("arms")
        if not pid:
            blockers.append(blocker("schedule-pair-id", f"pair[{index}] has no pair_id"))
        elif pid in seen:
            blockers.append(blocker("schedule-pair-id-duplicate", f"duplicate pair_id {pid}"))
        else:
            seen.add(pid)
        if not scenario:
            blockers.append(blocker("schedule-pair-scenario", f"pair[{index}] has no scenario"))
        if not isinstance(trial, int) or trial < 1:
            blockers.append(blocker("schedule-pair-trial", f"pair[{index}] has an invalid trial"))
        elif scenario:
            cell_key = f"{scenario}#{trial}"
            if cell_key in cell_seen:
                blockers.append(blocker("schedule-pair-duplicate-cell", f"pair[{index}] repeats {cell_key}; a record could satisfy two pairs"))
            cell_seen.add(cell_key)
        if order not in ("AB", "BA"):
            blockers.append(blocker("schedule-pair-order", f"pair[{index}] order must be AB or BA"))
        if not isinstance(pair_arms, list) or len(pair_arms) != 2 or (arms and pair_arms != [arms[0], arms[1]] and pair_arms != [arms[1], arms[0]]):
            blockers.append(blocker("schedule-pair-arms", f"pair[{index}] arms do not match schedule.arms"))
        elif arms and pair_arms != ([arms[0], arms[1]] if order == "AB" else [arms[1], arms[0]]):
            blockers.append(blocker("schedule-pair-order-arms", f"pair[{index}] arms do not follow declared order {order}"))
        if pair.get("status") == "complete":
            blockers.append(blocker(
                "schedule-pair-complete-unsupported",
                f"pair {pid} is marked complete; paired state is the evidence, not this immutable schedule",
            ))
        by_scenario.setdefault(scenario, []).append(order)

    for scenario, orders in by_scenario.items():
        if orders.count("AB") != orders.count("BA"):
            warnings.append(blocker("schedule-unbalanced", f"{scenario} has {orders.count('AB')} AB and {orders.count('BA')} BA trials"))
    return {"ok": not blockers, "blockers": blockers, "warnings": warnings, "schedule": data, "count": len(pairs)}


def validate_plan(plan_path: Path, snapshot: dict, scenarios_path: Path) -> dict:
    blockers, warnings = [], []
    data = _load_json(plan_path, "plan-json", blockers)
    if data is None:
        return {"ok": False, "blockers": blockers, "warnings": warnings, "plan": None}
    if data.get("schema") != RUN_PLAN_SCHEMA:
        blockers.append(blocker("plan-schema", f"plan.schema must be {RUN_PLAN_SCHEMA}"))
    for field in ("run_id", "phase", "arm"):
        if not str(data.get(field) or "").strip():
            blockers.append(blocker(f"plan-{field}", f"plan.{field} is required"))
    if snapshot.get("ok"):
        if data.get("project_id") != snapshot.get("project_id"):
            blockers.append(blocker("plan-project-mismatch", "plan.project_id does not match the snapshot"))
        declared = data.get("snapshot") if isinstance(data.get("snapshot"), dict) else {}
        if declared.get("sha256") and snapshot.get("snapshot_sha256") and str(declared["sha256"]).lower() != snapshot["snapshot_sha256"]:
            blockers.append(blocker("plan-snapshot-sha", "plan snapshot sha256 does not match the snapshot file"))
        if declared.get("config_hash") and snapshot.get("config_hash") and declared["config_hash"] != snapshot["config_hash"]:
            blockers.append(blocker("plan-config-hash", "plan config_hash does not match the snapshot"))
    else:
        blockers.append(blocker("plan-snapshot-unverified", "plan cannot bind to an unverified snapshot"))
    declared_set = data.get("set") if isinstance(data.get("set"), dict) else {}
    if not declared_set:
        blockers.append(blocker("plan-set-missing", "plan.set is required"))
    else:
        set_path = declared_set.get("path")
        actual_path = Path(set_path) if set_path and Path(set_path).is_absolute() else plan_path.parent / str(set_path or "")
        if not actual_path.is_file():
            actual_path = scenarios_path
        if not actual_path.is_file():
            blockers.append(blocker("plan-set-absent", "plan scenario set is absent"))
        else:
            actual = sha256_file(actual_path)
            if declared_set.get("sha256") and str(declared_set["sha256"]).lower() != actual:
                blockers.append(blocker("plan-set-sha", "scenario set changed since the plan was written"))
            if actual_path.resolve() != scenarios_path.resolve():
                blockers.append(blocker("plan-set-different", "plan names a different scenario set"))
    if data.get("pair_execution") is True:
        blockers.append(blocker("pair-execution-unimplemented", "plan requests pair execution; run_paired.mjs consumes per-arm plans and the schedule instead"))
    if data.get("collection_authorized") is False:
        blockers.append(blocker("plan-collection-not-authorized", "plan explicitly marks collection_authorized=false"))
    elif data.get("collection_authorized") is not True:
        warnings.append(blocker("plan-collection-unstated", "plan does not record collection_authorized=true"))
    if str(data.get("status") or "").strip().lower() in ("preparation_only", "preparation-only", "blocked", "draft", "not_ready", "not-ready"):
        blockers.append(blocker("plan-not-ready", f"plan status {data.get('status')!r} is not a ready collection state"))
    declared_schedule = data.get("schedule")
    if isinstance(declared_schedule, dict) and declared_schedule.get("path"):
        sched_path = Path(str(declared_schedule["path"]))
        if not sched_path.is_absolute():
            sched_path = plan_path.parent / sched_path
        if not sched_path.is_file():
            blockers.append(blocker("plan-schedule-absent", "plan pair schedule is absent"))
        else:
            actual_sched = sha256_file(sched_path)
            if declared_schedule.get("sha256") and str(declared_schedule["sha256"]).lower() != actual_sched:
                blockers.append(blocker("plan-schedule-sha", "pair schedule changed since the plan was written"))
            schedule_data = _load_json(sched_path, "plan-schedule-json", blockers)
            if isinstance(schedule_data, dict):
                if schedule_data.get("schema") != SCHEDULE_SCHEMA:
                    blockers.append(blocker("plan-schedule-schema", f"schedule schema must be {SCHEDULE_SCHEMA}"))
                if schedule_data.get("run_id") and data.get("run_id") and schedule_data["run_id"] != data["run_id"]:
                    blockers.append(blocker("plan-schedule-run-id", "plan run_id does not match the schedule"))
                if isinstance(schedule_data.get("arms"), list) and data.get("arm") and data["arm"] not in schedule_data["arms"]:
                    blockers.append(blocker("plan-schedule-arm", "plan arm is not in the schedule"))
    return {"ok": not blockers, "blockers": blockers, "warnings": warnings, "plan": data}


def _resolve_expected_path(value: str, repo_root: Path) -> Path:
    p = Path(value)
    return p if p.is_absolute() else (repo_root / p)


def _expected_hash(stage: str, rel: str, expect: dict | None, manifest: dict | None, blockers: list):
    if isinstance(expect, dict):
        files = expect.get("files")
        if isinstance(files, dict):
            for key, value in files.items():
                a = str(key).replace("\\", "/")
                b = rel.replace("\\", "/")
                if a.endswith(b) or b.endswith(a):
                    return value
        snapshot = expect.get("snapshot")
        if stage == "snapshot" and isinstance(snapshot, dict) and snapshot.get("sha256"):
            return snapshot["sha256"]
    if isinstance(manifest, dict):
        stages = manifest.get("stages") if isinstance(manifest.get("stages"), dict) else {}
        entry = stages.get(stage) if isinstance(stages.get(stage), dict) else {}
        if entry.get("sha256"):
            return entry["sha256"]
        artifacts = manifest.get("artifacts") if isinstance(manifest.get("artifacts"), dict) else {}
        for key, value in artifacts.items():
            a = str(key).replace("\\", "/")
            b = rel.replace("\\", "/")
            if a.endswith(b) or b.endswith(a):
                return value
    blockers.append(blocker(
        f"expected-hash-missing-{stage}",
        f"no expected sha256 for {rel}; add it to the manifest stage/artifacts or pass --expect",
    ))
    return None


def build_report(args) -> dict:
    """Pure builder used by the CLI and by tests."""
    repo_root = Path(args.repo_root).resolve() if args.repo_root else Path(__file__).resolve().parent.parent
    blockers: list = []
    warnings: list = []
    checks: list = []

    def add(result: dict, label: str):
        blockers.extend(result.get("blockers", []))
        warnings.extend(result.get("warnings", []))
        checks.append({"check": label, "ok": bool(result.get("ok")), "blockers": result.get("blockers", [])})

    guide = _resolve_expected_path(args.guide, repo_root)
    scenarios = _resolve_expected_path(args.scenarios, repo_root)
    graders = _resolve_expected_path(args.graders, repo_root)
    controls = _resolve_expected_path(args.controls, repo_root)
    manifest_path = _resolve_expected_path(args.manifest, repo_root)
    expect_path = _resolve_expected_path(args.expect, repo_root) if args.expect else None

    expect_data = None
    if expect_path:
        expect_data = _load_json(expect_path, "expect-json", blockers)
        if expect_data is not None and expect_data.get("schema") not in (None, EXPECT_SCHEMA):
            blockers.append(blocker("expect-schema", f"expect.schema must be {EXPECT_SCHEMA}"))

    if not guide.is_file() or not guide.read_text(encoding="utf-8", errors="replace").strip():
        blockers.append(blocker("guide-missing", f"human guide is missing or empty: {guide}"))
        checks.append({"check": "guide", "ok": False, "blockers": [blockers[-1]]})
    else:
        checks.append({"check": "guide", "ok": True, "blockers": []})

    scenario_report = validate_scenarios(scenarios, graders)
    add(scenario_report, "scenarios+graders")
    control_report = validate_controls(controls)
    add(control_report, "controls")
    manifest_report = validate_manifest(manifest_path, args.mode)
    add(manifest_report, "manifest")

    manifest_data = manifest_report.get("manifest")

    snapshot_path = Path(args.snapshot).resolve() if args.snapshot else None
    if snapshot_path is None and isinstance(manifest_data, dict):
        stages = manifest_data.get("stages") if isinstance(manifest_data.get("stages"), dict) else {}
        declared = stages.get("snapshot") if isinstance(stages.get("snapshot"), dict) else {}
        if declared.get("path"):
            snapshot_path = _resolve_expected_path(declared["path"], manifest_path.parent)
    if snapshot_path is None:
        blockers.append(blocker("snapshot-missing-arg", "no snapshot supplied via --snapshot or manifest.stages.snapshot.path"))
        snapshot_report = {"ok": False, "blockers": [], "warnings": []}
        checks.append({"check": "snapshot", "ok": False, "blockers": [blockers[-1]]})
    else:
        snapshot_report = validate_snapshot(snapshot_path)
        add(snapshot_report, "snapshot")
        try:
            inside_repo = snapshot_path.resolve().is_relative_to(repo_root.resolve())
        except AttributeError:
            try:
                snapshot_path.resolve().relative_to(repo_root.resolve())
                inside_repo = True
            except ValueError:
                inside_repo = False
        except ValueError:
            inside_repo = False
        if inside_repo and not getattr(args, "allow_public_snapshot", False):
            blockers.append(blocker(
                "snapshot-inside-repo",
                "raw capture artifacts are private by default; move the snapshot outside the repository or pass --allow-public-snapshot",
            ))

    plan_report = None
    if args.run_plan:
        plan_report = validate_plan(
            _resolve_expected_path(args.run_plan, repo_root),
            snapshot_report,
            scenarios,
        )
        add(plan_report, "run-plan")
        if plan_report.get("plan") and isinstance(manifest_data, dict):
            if plan_report["plan"].get("run_id") != manifest_data.get("run_id"):
                blockers.append(blocker("plan-manifest-run-id", "plan run_id does not match the manifest"))
            if plan_report["plan"].get("phase") != manifest_data.get("phase"):
                blockers.append(blocker("plan-manifest-phase", "plan phase does not match the manifest"))

    if args.phase:
        if isinstance(manifest_data, dict) and manifest_data.get("phase") and manifest_data["phase"] != args.phase:
            blockers.append(blocker("phase-manifest-mismatch", f"--phase {args.phase} does not match manifest phase {manifest_data['phase']}"))

    # Hash expectations for each configuration artifact.
    expected_pairs = [
        ("guide", guide, str(guide)),
        ("scenarios", scenarios, str(scenarios)),
        ("graders", graders, str(graders)),
        ("controls", controls, str(controls)),
    ]
    actual_hashes = {}
    for stage, path, label in expected_pairs:
        if not path.is_file():
            continue
        actual = sha256_file(path)
        actual_hashes[str(path)] = actual
        expected = _expected_hash(stage, label, expect_data, manifest_data, blockers)
        if expected is not None and str(expected).lower() != actual:
            blockers.append(blocker(f"hash-mismatch-{stage}", f"{label} changed: expected {expected}, got {actual}"))
    if snapshot_path and snapshot_path.is_file():
        actual_hashes[str(snapshot_path)] = sha256_file(snapshot_path)
        expected = _expected_hash("snapshot", "snapshot.json", expect_data, manifest_data, blockers)
        if expected is not None and str(expected).lower() != snapshot_report.get("snapshot_sha256"):
            blockers.append(blocker("hash-mismatch-snapshot", "snapshot file changed since the expectation was recorded"))

    if isinstance(manifest_data, dict):
        stages = manifest_data.get("stages") if isinstance(manifest_data.get("stages"), dict) else {}
        controls_entry = stages.get("controls") if isinstance(stages.get("controls"), dict) else {}
        results_entry = controls_entry.get("results") if isinstance(controls_entry.get("results"), dict) else {}
        if controls_entry.get("status") == "complete" and results_entry.get("path"):
            receipt_path = _resolve_expected_path(str(results_entry["path"]), manifest_path.parent)
            control_receipt = validate_control_results(
                receipt_path, controls, graders,
                actual_hashes.get(str(controls)), actual_hashes.get(str(graders)),
            )
            add(control_receipt, "control-results")
        labels_entry = stages.get("human_labels") if isinstance(stages.get("human_labels"), dict) else {}
        if labels_entry.get("status") == "complete" and labels_entry.get("path"):
            score_path = _resolve_expected_path(str(labels_entry["path"]), manifest_path.parent)
            blind_declared = labels_entry.get("blind_manifest") if isinstance(labels_entry.get("blind_manifest"), dict) else {}
            blind_manifest = _resolve_expected_path(args.blind_manifest, repo_root) if getattr(args, "blind_manifest", None) else None
            if blind_manifest is None and blind_declared.get("path"):
                blind_manifest = _resolve_expected_path(str(blind_declared["path"]), manifest_path.parent)
            if blind_declared.get("path") and not blind_declared.get("sha256"):
                blockers.append(blocker("human-labels-blind-manifest-sha-missing", "stages.human_labels.blind_manifest must bind sha256"))
            returned_declared = labels_entry.get("returned_sheet") if isinstance(labels_entry.get("returned_sheet"), dict) else {}
            returned_sheet = _resolve_expected_path(args.returned_sheet, repo_root) if getattr(args, "returned_sheet", None) else None
            if returned_sheet is None and returned_declared.get("path"):
                returned_sheet = _resolve_expected_path(str(returned_declared["path"]), manifest_path.parent)
            if returned_declared.get("path") and not returned_declared.get("sha256"):
                blockers.append(blocker("human-labels-returned-sheet-sha-missing", "stages.human_labels.returned_sheet must bind sha256"))
            if blind_manifest is None:
                blockers.append(blocker(
                    "human-labels-blind-manifest-missing",
                    "a complete human-label stage must bind the frozen calibration blind manifest (--blind-manifest or stages.human_labels.blind_manifest)",
                ))
            elif blind_declared.get("sha256"):
                if is_placeholder_hash(blind_declared.get("sha256")) or sha256_file(blind_manifest) != str(blind_declared["sha256"]).lower():
                    blockers.append(blocker("human-labels-blind-manifest-sha", "calibration blind manifest changed since the manifest was written"))
            if returned_sheet is None:
                blockers.append(blocker(
                    "human-labels-returned-sheet-missing",
                    "a complete human-label stage must bind the returned labelled CSV (--returned-sheet or stages.human_labels.returned_sheet)",
                ))
            elif returned_declared.get("sha256"):
                if is_placeholder_hash(returned_declared.get("sha256")) or sha256_text_file(returned_sheet) != str(returned_declared["sha256"]).lower():
                    blockers.append(blocker("human-labels-returned-sheet-sha", "returned labelled CSV changed since the manifest was written"))
            scoring = validate_scoring_receipt(
                score_path, guide,
                blind_manifest_path=blind_manifest,
                returned_sheet_path=returned_sheet,
                reviewed_attested=labels_entry.get("reviewed") is True,
            )
            add(scoring, "human-label-score")
        pair_execution = manifest_data.get("pair_execution") if isinstance(manifest_data.get("pair_execution"), dict) else {}
        if pair_execution.get("implemented") is True and not (repo_root / "evals" / "run_paired.mjs").is_file():
            blockers.append(blocker("pair-executor-missing", "manifest says pair execution is implemented, but evals/run_paired.mjs is absent"))

    schedule_report = None
    schedule_path = None
    if args.schedule:
        schedule_path = _resolve_expected_path(args.schedule, repo_root)
    elif isinstance(manifest_data, dict):
        pair_execution = manifest_data.get("pair_execution") if isinstance(manifest_data.get("pair_execution"), dict) else {}
        declared = pair_execution.get("schedule") if isinstance(pair_execution.get("schedule"), dict) else {}
        if pair_execution.get("planned") is True and not declared.get("path"):
            warnings.append(blocker(
                "schedule-not-declared",
                "manifest plans pair execution but declares no schedule; pair execution remains unavailable",
            ))
        if declared.get("path"):
            schedule_path = _resolve_expected_path(declared["path"], manifest_path.parent)
    if schedule_path:
        schedule_report = validate_schedule(schedule_path)
        add(schedule_report, "pair-schedule")

    ready = not blockers
    return {
        "schema": PREFLIGHT_SCHEMA,
        "mode": args.mode,
        "ready": ready,
        "repo_root": str(repo_root),
        "blockers": blockers,
        "warnings": warnings,
        "checks": checks,
        "hashes": actual_hashes,
        "snapshot": {
            "path": str(snapshot_path) if snapshot_path else None,
            "status": snapshot_report.get("status"),
            "ok": snapshot_report.get("ok"),
            "project_id": snapshot_report.get("project_id"),
            "model": snapshot_report.get("model"),
            "current_effective_config_verified": snapshot_report.get("current_effective_config_verified"),
            "config_hash": snapshot_report.get("config_hash"),
            "blockers": snapshot_report.get("blockers", []),
        } if snapshot_path else None,
        "manifest": {
            "path": str(manifest_path),
            "status": "complete" if manifest_data else "missing",
            "run_id": manifest_report.get("run_id"),
            "phase": manifest_report.get("phase"),
        },
        "schedule": {
            "path": str(schedule_path) if schedule_path else None,
            "pairs": schedule_report.get("count") if schedule_report else 0,
            "pair_execution_implemented": False,
        } if schedule_path else None,
        "limitations": [
            "Preflight is offline: it cannot prove the platform's live behaviour.",
            "A verified snapshot proves the captured artifacts hash; it does not prove the platform is serving them now.",
            "Paired execution exists via evals/run_paired.mjs; no pair is collected or counted without per-arm records and ordered capture timestamps.",
        ],
    }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="evals/preflight.py",
        description="Offline, fail-closed preflight for the next Agentplace capture. Reads only; --help writes nothing.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Defaults: evals/human/GUIDE.md, datasets/next-run/scenarios.json,\n"
            "datasets/next-run/graders.json, evals/human/controls.json,\n"
            "evals/next_run/MANIFEST.json. A missing real guide, fresh cases,\n"
            "controls file, manifest, snapshot, or configuration artifact is reported as\n"
            "an actionable blocker; it is never silently invented.\n\n"
            "Exit codes: 0 ready, 1 blocked, 2 usage."
        ),
    )
    parser.add_argument("--mode", choices=("capture", "scoring"), default="capture",
                        help="capture readiness or scoring readiness; both require completed and reviewed human labels")
    parser.add_argument("--guide", default="evals/human/GUIDE.md")
    parser.add_argument("--scenarios", default="datasets/next-run/scenarios.json")
    parser.add_argument("--graders", default="datasets/next-run/graders.json")
    parser.add_argument("--controls", default="evals/human/controls.json")
    parser.add_argument("--manifest", default="evals/next_run/MANIFEST.json")
    parser.add_argument("--snapshot", default=None, help="effective-config snapshot (private)")
    parser.add_argument("--run-plan", default=None)
    parser.add_argument("--blind-manifest", default=None, help="private agentplace-blind-manifest/1 for score cross-checks")
    parser.add_argument("--returned-sheet", default=None, help="returned labelled sheet.csv for returned_sheet_sha256 verification")
    parser.add_argument("--schedule", default=None)
    parser.add_argument("--expect", default=None, help="preflight expectation JSON of file -> sha256")
    parser.add_argument("--phase", default=None)
    parser.add_argument("--repo-root", default=None)
    parser.add_argument("--json", action="store_true", help="print the machine-readable report")
    parser.add_argument("--write-report", default=None, help="write the report to this path (default: stdout only)")
    parser.add_argument("--print-schemas", action="store_true", help="print the planning JSON field map and exit; reads and writes nothing")
    parser.add_argument("--allow-public-snapshot", action="store_true", help="permit a snapshot stored inside the repository (raw artifacts are private by default)")
    return parser


def main(argv=None) -> int:
    parser = build_parser()
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:  # --help / usage
        return int(exc.code or 0)
    if args.print_schemas:
        print(json.dumps(SCHEMAS, indent=1, ensure_ascii=False))
        return 0
    report = build_report(args)
    if args.write_report:
        out = Path(args.write_report)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(report, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    if args.json:
        print(json.dumps(report, indent=1, ensure_ascii=False))
    else:
        print(f"preflight: {report['mode']} — {'READY' if report['ready'] else 'BLOCKED'}")
        print(f"repo      : {report['repo_root']}")
        if report["snapshot"]:
            print(f"snapshot  : {report['snapshot']['status']} {report['snapshot']['path']}")
        print(f"manifest  : {report['manifest']['status']} {report['manifest']['path']}")
        if report["schedule"]:
            print(f"schedule  : {report['schedule']['pairs']} pairs (paired executor separate; completion requires state)")
        if report["warnings"]:
            print("\nwarnings:")
            for item in report["warnings"]:
                print(f"  ! [{item['code']}] {item['message']}")
        if report["blockers"]:
            print("\nblockers:")
            for item in report["blockers"]:
                print(f"  ✗ [{item['code']}] {item['message']}")
        else:
            print("\nall checks passed")
    return 0 if report["ready"] else 1


