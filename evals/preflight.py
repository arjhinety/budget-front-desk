#!/usr/bin/env python3
"""
Offline preflight for the next Agentplace capture.

Checks, without a browser and without the network:
  * the human guide exists and is non-empty
  * the scenario set parses, has unique ids, and carries the text the grader expects
  * every scenario has a prospective grader in the matching graders file
  * a controls file exists with unique control ids and a passed
    agentplace-control-results-v1 receipt covering every declared control
  * the effective-config snapshot verifies: model Luna, a real capture method,
    relative hashed artifacts for instructions/knowledge/UI settings, and no
    placeholder/empty/intended-only evidence
  * guide/scenarios/graders/controls/snapshot hashes match an expectation
  * the run manifest explicitly sets collection_authorized=true with a ready
    status, declares every stage, and binds a completed, reviewed modern
    agentplace-blind-score/1 receipt for human labels
  * a pair schedule, when supplied, is well formed and never claims execution

Defaults are the next-run paths: evals/human/GUIDE.md,
datasets/next-run/scenarios.json, datasets/next-run/graders.json,
evals/human/controls.json, evals/next_run/MANIFEST.json. Historical sets are
available only through explicit --scenarios/--graders flags, so omitting a flag
cannot silently validate old development tests as the next fresh run.

This module exports the schema constants and validators so the next protocol and
planning JSON can be written against one definition:

    from preflight import (
        SNAPSHOT_SCHEMA, RUN_PLAN_SCHEMA, SCHEDULE_SCHEMA, MANIFEST_SCHEMA,
        EXPECT_SCHEMA, SCORING_RECEIPT_SCHEMA, CONTROL_RESULTS_SCHEMA,
        validate_snapshot, validate_manifest, validate_control_results,
        validate_scoring_receipt, build_report, main,
    )

Exit codes: 0 ready, 1 blocked, 2 usage. `--help` reads and writes nothing.
"""

