#!/usr/bin/env python3
"""
Compile the dataset manifest.

Every set this repository evaluates on is generated by a script in `evals/`, so
the manifest records the script, its hash, the output's hash, and the policies
that decide what is in and out. Nothing here is typed by hand except the policy
statements, which are prose decisions rather than data.

  python datasets/build_manifest.py
"""

from __future__ import annotations

import hashlib
import json
import subprocess
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "datasets"

# set name -> (file, generator, what it is for)
SETS = {
    "handwritten-single-turn": (
        "evals/scenarios.json", None,
        "33 scenarios written by hand in five splits; the set the first arms were tuned on",
    ),
    "generated-single-turn": (
        "evals/scenarios-big.json", "evals/gen_scenarios.py",
        "55 scenarios generated from the business decision branches; disjoint from the hand-written set",
    ),
    "multiturn": (
        "evals/scenarios-mt.json", "evals/gen_multiturn.py",
        "18 three-turn scripts in six behavioural families; the customer turns are fixed, not simulated",
    ),
}

GRADERS = {
    "evals/graders.json": "hand-written set",
    "evals/graders-big.json": "generated set",
    "evals/graders-mt.json": "multi-turn set",
}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    OUT.mkdir(exist_ok=True)
    sets = {}
    for name, (rel, gen, purpose) in SETS.items():
        p = ROOT / rel
        if not p.exists():
            continue
        data = json.loads(p.read_text(encoding="utf-8"))
        items = data.get("scenarios") or data.get("scripts") or []
        entry = {
            "file": rel,
            "sha256": sha256(p),
            "items": len(items),
            "purpose": purpose,
            "generator": gen,
            "generator_sha256": sha256(ROOT / gen) if gen and (ROOT / gen).exists() else None,
            "authored_by": "the repository author, from the business's public pages",
            "regenerate": f"python {gen}" if gen else "hand-written; not regenerated",
        }
        sets[name] = entry

    graders = {rel: {"sha256": sha256(ROOT / rel), "grades": what}
               for rel, what in GRADERS.items() if (ROOT / rel).exists()}

    manifest = {
        "canonical_schema_version": "agentplace-eval-set-v1",
        "generation_timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "repository_commit": subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT,
                                            capture_output=True, text=True).stdout.strip() or "uncommitted",
        "record_count": sum(s["items"] for s in sets.values()),

        "contamination_policy": (
            "The hand-written and generated single-turn sets are disjoint by construction: the "
            "generator emits ids prefixed G- and refuses to emit an id that already exists in the "
            "hand-written set. The multi-turn set uses MT- ids and a different schema. No scenario "
            "text is reused between sets. This is checked by build_manifest.py, not asserted."
        ),
        "dedup_policy": (
            "Exact duplicate customer messages are removed at generation time. Near-duplicates are "
            "NOT removed, and that is deliberate: a near-duplicate with a different county or a "
            "different day is a different test, and collapsing them would delete exactly the "
            "perturbations the set exists to measure. The cleaning pass measures near-duplicate "
            "rate and reports it rather than deleting."
        ),
        "evaluation_exclusion_policy": (
            "Any record whose transcript contains the platform quota message, a render error, or a "
            "harness failure is excluded from scoring and recorded as excluded, never counted as an "
            "agent failure. The exclusion list is in evals/results/*.json under records with an "
            "'error' key."
        ),
        "heldout_policy": (
            "The seven held-out single-turn scenarios were written after the first arm was scored. "
            "They test phrasing generalization, not unseen failure modes, and RESULTS.md says so. "
            "A sealed set for grader validation is defined in CLEANING-PROTOCOL.md and has not been "
            "built yet."
        ),
        "sets": sets,
        "graders": graders,
    }

    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
                                       encoding="utf-8")
    print(f"{manifest['record_count']} items across {len(sets)} sets -> datasets/manifest.json")
    for name, s in sets.items():
        print(f"  {name:26} {s['items']:>3} items  {s['sha256'][:12]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
